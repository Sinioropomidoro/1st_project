#include <stdio.h>

int main() {

	char ch = 63;
	unsigned char uch = 'r';
	short j = 'b', k = 98;

	printf("%c == %d\n", ch, ch);
	printf("%c == %d\n", uch, uch);
	printf("%c == %c\n", j, k);

	return 0;
}
// ? == 63Знак вопроса ? имеет порядковый номер 63 в таблице ASCII. Программа вывела сначала сам символ, а затем его числовое значение.
// r == 114Строчная английская буква r имеет порядковый номер 114 в таблице ASCII.
// b == bЗдесь вместо числа снова вывелся символ b. Скорее всего, в коде программы для этой строчки была допущена
// если бы стоял %d вместо %c вывелась бы буква b под 98 номеров в формате ASCII.